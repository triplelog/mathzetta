#!/usr/bin/env node
// rules/calculus.yaml and rules/cas/*.yaml → src/cas/default-rules.js, so createCAS()
// has its rules with no file reading (in Node and in a browser). The YAML files are
// the source; run `npm run build:rules` after editing them (a test checks it was).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const RULE_FILES = ['rules/calculus.yaml', ...readdirSync(`${root}rules/cas`).filter((f) => f.endsWith('.yaml')).sort().map((f) => `rules/cas/${f}`)];

export const COMPLEX_FILES = readdirSync(`${root}rules/cas/complex`).filter((f) => f.endsWith('.yaml')).sort().map((f) => `rules/cas/complex/${f}`);

export function bundle() {
  const list = (files) => files.map((f) => `  // ${f}\n  ${JSON.stringify(readFileSync(root + f, 'utf8'))},`).join('\n');
  return `// Generated by tools/bundle-rules.mjs from rules/calculus.yaml and rules/cas/. Edit those, then npm run build:rules.\n`
    + `export const DEFAULT_RULES = [\n${list(RULE_FILES)}\n];\n\n// added by createCAS({ complex: true })\nexport const COMPLEX_RULES = [\n${list(COMPLEX_FILES)}\n];\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(`${root}src/cas/default-rules.js`, bundle());
  console.log(`src/cas/default-rules.js: ${[...RULE_FILES, ...COMPLEX_FILES].join(', ')}`);
}
